def make_multiasset_ohlcv(n_tickers: int, n_days: int, seed: int = SEED) -> tuple[pd.DataFrame, list[str]]:
    """Build a DataFrame in the exact (ticker, feature) MultiIndex-column format
    the BacktestingEngine's DataHandler consumes."""
    rng = np.random.default_rng(seed)
    tickers = [f"T{i:03d}" for i in range(n_tickers)]
    dates = pd.bdate_range("2020-01-01", periods=n_days)
    frames = {}
    for tk in tickers:
        rets = rng.normal(0.0004, 0.012, n_days)
        price = 100 * np.exp(np.cumsum(rets))
        frames[(tk, "adj_close")] = price
        frames[(tk, "close")] = price
        frames[(tk, "volume")] = rng.integers(1e6, 5e6, n_days).astype(float)
    df = pd.DataFrame(frames, index=dates)
    df.columns = pd.MultiIndex.from_tuples(df.columns)
    return df, tickers


def load_real_returns() -> pd.DataFrame:
    """Load the newest feature CSV set into a wide log-return frame (real 7 assets)."""
    files = [os.path.join(ROOT, "tests", "fixtures", "feat_ohlcv_sample.csv")]
