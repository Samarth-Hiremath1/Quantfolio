def bench_optimizer() -> dict:
    print("[2/6] Portfolio optimizer ...")
    out: dict = {"description": "scipy SLSQP max-Sharpe / min-vol. Runtime, convergence, in-sample Sharpe uplift."}

    # (a) Runtime + convergence scaling with #assets (synthetic cov)
    runtime = []
    for n in [5, 10, 25, 50, 100]:
        rng = np.random.default_rng(SEED + n)
        rets = pd.DataFrame(rng.normal(0.0005, 0.012, (600, n)),
                            columns=[f"A{i}" for i in range(n)])
        t0 = time.perf_counter()
        mu = rets.mean() * 252
        cov = rets.cov() * 252
        cov_t = time.perf_counter() - t0

        opt = PortfolioOptimizer(mu, cov)
        t0 = time.perf_counter()
        w = opt.maximize_sharpe()
        opt_t = time.perf_counter() - t0
        # convergence check via scipy result
        from scipy.optimize import minimize
        res = minimize(opt._neg_sharpe_ratio, np.ones(n) / n, method="SLSQP",
                       bounds=tuple((0.0, 1.0) for _ in range(n)),
                       constraints=({"type": "eq", "fun": lambda x: np.sum(x) - 1}))
        runtime.append({
            "n_assets": n,
            "cov_computation_ms": round(cov_t * 1e3, 3),
            "maximize_sharpe_ms": round(opt_t * 1e3, 3),
            "converged": bool(res.success),
            "iterations": int(res.get("nit", -1)),
            "weight_sum": round(float(w.sum()), 6),
        })
        print(f"      {n:>3} assets: opt {opt_t*1e3:.1f} ms, cov {cov_t*1e3:.2f} ms, converged={res.success}")
    out["scaling"] = runtime

    # (b) In-sample Sharpe uplift on REAL data (7 assets, ~2 months) — honest, small-sample
    real = load_real_returns()
    real_block: dict
    if real.shape[0] >= 10 and real.shape[1] >= 2:
        mu = real.mean() * 252
        cov = real.cov() * 252
        opt = PortfolioOptimizer(mu, cov, risk_free_rate=0.02)
        w_opt = opt.maximize_sharpe()
        rk = RiskMetrics(risk_free_rate=0.02)

        def port_stats(weights):
            pr = real.dot(weights.reindex(real.columns).fillna(0.0))
            return {
                "annualized_return": round(float(pr.mean() * 252), 4),
                "annualized_volatility": round(float(pr.std() * np.sqrt(252)), 4),
                "sharpe_ratio": round(float(rk.compute_sharpe_ratio(pr)), 4),
                "max_drawdown": round(float(rk.compute_max_drawdown(pr)), 4),
            }

        eq = pd.Series(1.0 / real.shape[1], index=real.columns)
        eq_stats = port_stats(eq)
        opt_stats = port_stats(w_opt)
        real_block = {
            "status": "measured_in_sample",
            "n_assets": int(real.shape[1]),
            "n_observations": int(real.shape[0]),
            "tickers": list(real.columns),
            "equal_weight": eq_stats,
            "max_sharpe_optimized": opt_stats,
            "sharpe_uplift_abs": round(opt_stats["sharpe_ratio"] - eq_stats["sharpe_ratio"], 4),
            "caveat": (
                "IN-SAMPLE on ~2 months of daily data. The optimizer is handed the same "
                "sample mean/cov it is scored on, so the Sharpe uplift is an upper bound and "
                "NOT evidence of out-of-sample skill. Reportable as an engineering result "
                "(optimizer works, weights sum to 1, produces the max-Sharpe point), not as alpha."
            ),
        }
        print(f"      real in-sample Sharpe: equal-weight {eq_stats['sharpe_ratio']} -> "
              f"optimized {opt_stats['sharpe_ratio']}")
    else:
        real_block = {"status": "not_measured", "reason": "insufficient real return observations"}
    out["real_in_sample_uplift"] = real_block

    # (c) efficient_frontier runtime (7 real assets or synthetic)
    n = 10
    rng = np.random.default_rng(SEED)
    rets = pd.DataFrame(rng.normal(0.0005, 0.012, (600, n)), columns=[f"A{i}" for i in range(n)])
    opt = PortfolioOptimizer(rets.mean() * 252, rets.cov() * 252)
    t0 = time.perf_counter()
    tr, tv, _ = opt.efficient_frontier(points=50)
    out["efficient_frontier_50pts_ms"] = round((time.perf_counter() - t0) * 1e3, 2)
    out["efficient_frontier_converged_pts"] = int(np.sum(~np.isnan(tv)))

    # Chart
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(11, 4.2))
    a1.plot([r["n_assets"] for r in runtime], [r["maximize_sharpe_ms"] for r in runtime],
            "o-", color=C1, lw=2, label="max-Sharpe")
    a1.plot([r["n_assets"] for r in runtime], [r["cov_computation_ms"] for r in runtime],
            "s--", color=C3, lw=2, label="cov matrix")
    a1.legend(); _style(a1, "Optimizer runtime vs #assets", "# assets", "milliseconds")
    a2.plot(tv, tr, "-", color=C2, lw=2)
    _style(a2, "Efficient frontier (10 synthetic assets)", "volatility", "return")
    fig.tight_layout()
    fig.savefig(os.path.join(CHARTS, "optimizer_runtime.png"), dpi=130)
    plt.close(fig)
    return out


