def _pctl(xs, p):
    return round(float(np.percentile(xs, p)), 3)


def bench_api() -> dict:
    print("[6/6] API latency (in-process TestClient, SQLite-backed) ...")
    db = os.path.join(CHARTS, "_bench_api.db")
    if os.path.exists(db):
        os.remove(db)
    os.environ["POSTGRES_URL"] = f"sqlite:///{db}"
    try:
        tickers = _seed_sqlite(f"sqlite:///{db}")
        from fastapi.testclient import TestClient
        from api.main import app
    except Exception as e:  # pragma: no cover
        return {"status": "not_measured", "reason": f"could not boot in-process API: {e}"}

    calls = {
        "GET /health": ("get", "/health", None),
        "POST /portfolio/optimize": ("post", "/api/v1/portfolio/optimize",
                                     {"tickers": tickers[:5], "objective": "sharpe"}),
        "POST /portfolio/risk": ("post", "/api/v1/portfolio/risk",
                                 {"tickers": tickers[:3], "weights": {t: 1/3 for t in tickers[:3]}}),
        "POST /forecast (Ridge_AR)": ("post", "/api/v1/forecast",
                                      {"tickers": tickers[:3], "model_type": "Ridge_AR"}),
        "POST /backtest (BuyAndHold)": ("post", "/api/v1/backtest",
                                        {"tickers": tickers[:3], "strategy": "BuyAndHold"}),
    }
    results = {}
    with TestClient(app) as client:
        for name, (verb, path, body) in calls.items():
            fn = getattr(client, verb)
            # warmup
            for _ in range(3):
                r = fn(path) if body is None else fn(path, json=body)
            if r.status_code != 200:
                results[name] = {"status": "error", "code": r.status_code, "detail": r.text[:200]}
                print(f"      {name:<30} ERROR {r.status_code}")
                continue
            n = 50 if verb == "post" else 200
            lat = []
            for _ in range(n):
                t0 = time.perf_counter()
                fn(path) if body is None else fn(path, json=body)
                lat.append((time.perf_counter() - t0) * 1e3)
            results[name] = {
                "n": n, "p50_ms": _pctl(lat, 50), "p95_ms": _pctl(lat, 95),
                "p99_ms": _pctl(lat, 99), "mean_ms": round(float(np.mean(lat)), 3),
            }
            print(f"      {name:<30} p50={results[name]['p50_ms']:.2f}ms  p95={results[name]['p95_ms']:.2f}ms")

    if os.path.exists(db):
        os.remove(db)

    # Chart
    labelled = {k: v for k, v in results.items() if "p50_ms" in v}
    if labelled:
        names = list(labelled.keys())
        y = np.arange(len(names))
        fig, ax = plt.subplots(figsize=(11, 4.4))
        ax.barh(y, [labelled[n]["p50_ms"] for n in names], color=C1, label="p50")
        ax.barh(y, [labelled[n]["p95_ms"] - labelled[n]["p50_ms"] for n in names],
                left=[labelled[n]["p50_ms"] for n in names], color=C2, label="p50→p95")
        ax.set_yticks(y); ax.set_yticklabels([n.replace("POST ", "").replace("GET ", "") for n in names], fontsize=8)
        _style(ax, "In-process API latency (SQLite, no network)", "milliseconds", "")
        ax.legend()
        fig.tight_layout()
        fig.savefig(os.path.join(CHARTS, "api_latency.png"), dpi=130)
        plt.close(fig)

    return {
        "description": (
            "Latency of the REAL FastAPI routes via Starlette TestClient, backed by a SQLite copy of "
            "the shipped data. In-process: excludes network RTT, Postgres, and container overhead, so "
            "these are LOWER bounds on production latency — but they exercise the actual route + query "
            "+ compute path (all endpoints now functional; see KNOWN_ISSUES.md D-01/03/06)."
        ),
        "endpoints": results,
        "not_measured": {
            "network_and_postgres": "TestClient is in-process; real deployment adds network + Postgres latency.",
            "docker_startup": "Requires `docker-compose up`; poll /health to time to-healthy.",
            "concurrency_and_cpu": "Requires a running server + load tool (hey/wrk) and `docker stats`.",
        },
    }


