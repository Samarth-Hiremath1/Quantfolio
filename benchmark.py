def bench_backtesting() -> dict:
    print("[1/6] Backtesting engine ...")
    out: dict = {"description": "Event-driven engine throughput. Synthetic OHLCV, real SMA(10/50) crossover strategy (signals fire on crossover, not every bar)."}

    # (a) Scaling across number of securities at fixed horizon
    n_days = 252
    scale = []
    for n_tk in [7, 25, 50, 100, 200]:
        data, tickers = make_multiasset_ohlcv(n_tk, n_days)
        gc.collect()
        tracemalloc.start()
        t0 = time.perf_counter()
        eng = BacktestingEngine(data=data, tickers=tickers, strategy_class=MLForecastStrategy, model=None)
        eng.run()
        elapsed = time.perf_counter() - t0
        _, peak = tracemalloc.get_traced_memory()
        tracemalloc.stop()
        market_events = n_days
        total_events = market_events + eng.signals + eng.orders + eng.fills
        scale.append({
            "n_securities": n_tk,
            "n_days": n_days,
            "wall_time_s": round(elapsed, 4),
            "bars_per_s": round(n_days / elapsed, 1),
            "total_events": total_events,
            "events_per_s": round(total_events / elapsed, 1),
            "signals": eng.signals, "orders": eng.orders, "fills": eng.fills,
            "peak_python_mem_mb": round(peak / 1e6, 2),
        })
        print(f"      {n_tk:>3} securities: {total_events/elapsed:,.0f} events/s, "
              f"{n_days/elapsed:,.0f} bars/s, peak {peak/1e6:.1f} MB")
    out["scaling_by_securities"] = scale

    # (b) Scaling across horizon at fixed 7 securities (time complexity check)
    horizon = []
    for n_days in [252, 1260, 2520]:
        data, tickers = make_multiasset_ohlcv(7, n_days)
        t0 = time.perf_counter()
        eng = BacktestingEngine(data=data, tickers=tickers, strategy_class=MLForecastStrategy, model=None)
        eng.run()
        elapsed = time.perf_counter() - t0
        total_events = n_days + eng.signals + eng.orders + eng.fills
        horizon.append({
            "n_securities": 7, "n_days": n_days,
            "wall_time_s": round(elapsed, 4),
            "bars_per_s": round(n_days / elapsed, 1),
            "events_per_s": round(total_events / elapsed, 1),
        })
    out["scaling_by_horizon"] = horizon

    # Complexity note: events per bar grow linearly with securities -> O(days * securities)
    base = scale[0]["events_per_s"]
    out["complexity"] = {
        "model": "O(n_days * n_securities) events; single-threaded Python queue.Queue loop",
        "bottleneck": "Per-event Python object creation + queue.get/put overhead; strategy loops over every ticker each bar.",
        "throughput_stability_events_per_s": {s["n_securities"]: s["events_per_s"] for s in scale},
    }

    # Chart
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(11, 4.2))
    xs = [s["n_securities"] for s in scale]
    a1.plot(xs, [s["events_per_s"] for s in scale], "o-", color=C1, lw=2)
    _style(a1, "Engine throughput vs #securities", "# securities", "events / sec")
    a1.ticklabel_format(style="plain", axis="y")
    xs2 = [h["n_days"] for h in horizon]
    a2.plot(xs2, [h["wall_time_s"] for h in horizon], "o-", color=C2, lw=2)
    _style(a2, "Wall time vs horizon (7 assets)", "# trading days", "seconds")
    fig.tight_layout()
    fig.savefig(os.path.join(CHARTS, "backtesting_throughput.png"), dpi=130)
    plt.close(fig)
    return out


