def _seed_sqlite(db_url: str):
    from sqlalchemy import create_engine
    engine = create_engine(db_url)
    raw = pd.read_csv([os.path.join(ROOT, "tests", "fixtures", "raw_ohlcv_sample.csv")][-1])
