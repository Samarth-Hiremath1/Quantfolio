# 4. ML WALK-FORWARD (honest forecasting benchmark)
# =========================================================================== #
def _fit_lstm_predict(y_train: np.ndarray, horizon: int, seq_len: int = 20,
                      epochs: int = 40) -> np.ndarray:
    """Train UnivariateLSTM on a returns window; forecast `horizon` steps.
    Uses the repo model class. Deterministic (seeded)."""
    import torch
    from models.forecasting.lstm_model import UnivariateLSTM, create_sequences
    torch.manual_seed(SEED)
    if len(y_train) < seq_len + horizon + 5:
        return np.repeat(y_train[-1], horizon)
    X, Y = create_sequences(y_train.astype(np.float32), seq_len, horizon)
    Xt = torch.tensor(X, dtype=torch.float32)
    Yt = torch.tensor(Y, dtype=torch.float32)
    model = UnivariateLSTM(input_size=1, hidden_size=32, num_layers=1, output_size=horizon)
    opt = torch.optim.Adam(model.parameters(), lr=1e-2)
    loss_fn = torch.nn.MSELoss()
    model.train()
    for _ in range(epochs):
        opt.zero_grad()
        pred = model(Xt)
        loss = loss_fn(pred, Yt)
        loss.backward()
        opt.step()
    model.eval()
    with torch.no_grad():
        last = torch.tensor(y_train[-seq_len:].astype(np.float32)).reshape(1, seq_len, 1)
        return model(last).numpy().ravel()


def _metrics(actuals, preds) -> dict:
    from sklearn.metrics import mean_squared_error, mean_absolute_error, r2_score
    a = np.asarray(actuals, float); p = np.asarray(preds, float)
    mse = mean_squared_error(a, p)
    return {
        "mse": float(mse),
        "rmse": float(np.sqrt(mse)),
        "mae": float(mean_absolute_error(a, p)),
        "r2": float(r2_score(a, p)),
        "directional_accuracy": float(np.mean(np.sign(a) == np.sign(p))),
        "n": int(len(a)),
    }


def _run_walkforward(y: pd.Series, label: str, include_lstm: bool = True) -> dict:
    horizon = 5
    val = WalkForwardValidator(min_train_size=252, step_size=63)

    def last_value(yt):        # persistence: repeat last observed return
        return np.repeat(yt.iloc[-1], horizon)

    def moving_average(yt):    # mean of last 21
        return np.repeat(yt.iloc[-21:].mean(), horizon)

    def mean_predictor(yt):    # full-history mean
        return np.repeat(yt.mean(), horizon)

    def linear_regression(yt):
        from sklearn.linear_model import LinearRegression
        lag = 5
        arr = yt.values
        X = np.column_stack([arr[i:len(arr) - lag + i] for i in range(lag)])
        target = arr[lag:]
        lr = LinearRegression().fit(X[:-1], target[:len(target) - 0][:len(X) - 1]) \
            if len(X) > 2 else None
        if lr is None:
            return np.repeat(arr[-1], horizon)
        window = list(arr[-lag:])
        preds = []
        for _ in range(horizon):
            nxt = lr.predict(np.array(window[-lag:]).reshape(1, -1))[0]
            preds.append(nxt); window.append(nxt)
        return np.array(preds)

    models = {
        "last_value": last_value,
        "moving_average_21": moving_average,
        "historical_mean": mean_predictor,
        "linear_regression_ar5": linear_regression,
    }

    results = {}
    for name, fn in models.items():
        r = val.evaluate(y, fn, horizon=horizon)
        results[name] = _metrics(r["actuals"], r["predictions"])
        print(f"      [{label}] {name:<22} MSE={results[name]['mse']:.3e} "
              f"DA={results[name]['directional_accuracy']:.3f}")

    # ARIMA baseline (repo helper)
    try:
        ar = val.evaluate_arima_baseline(y, order=(1, 0, 0), horizon=horizon)
        results["arima_1_0_0"] = _metrics(ar["actuals"], ar["predictions"])
        print(f"      [{label}] {'arima_1_0_0':<22} MSE={results['arima_1_0_0']['mse']:.3e} "
              f"DA={results['arima_1_0_0']['directional_accuracy']:.3f}")
    except Exception as e:
        results["arima_1_0_0"] = {"status": "failed", "reason": str(e)[:120]}

    # LSTM (repo model, trained per fold)
    if include_lstm:
        def lstm_fn(yt):
            return _fit_lstm_predict(yt.values, horizon)
        r = val.evaluate(y, lstm_fn, horizon=horizon)
        results["univariate_lstm"] = _metrics(r["actuals"], r["predictions"])
        print(f"      [{label}] {'univariate_lstm':<22} MSE={results['univariate_lstm']['mse']:.3e} "
              f"DA={results['univariate_lstm']['directional_accuracy']:.3f}")

    # Rank by MSE and compute uplift vs last_value
    ranked = sorted([(k, v) for k, v in results.items() if "mse" in v], key=lambda kv: kv[1]["mse"])
    lv = results["last_value"]["mse"]
    for k, v in results.items():
        if "mse" in v:
            v["mse_vs_last_value_pct"] = round((lv - v["mse"]) / lv * 100, 2)
    return {"models": results, "best_by_mse": ranked[0][0], "n_folds_note": "min_train=252, step=63, horizon=5"}


def bench_ml() -> dict:
    print("[4/6] ML walk-forward (this trains an LSTM per fold; ~1-2 min) ...")
    out: dict = {
        "description": (
            "Expanding-window walk-forward CV via the repo's WalkForwardValidator, comparing the "
            "repo UnivariateLSTM against last-value, moving-average, historical-mean, AR(5) linear "
            "regression and ARIMA(1,0,0). Run on TWO synthetic series to show honest behaviour."
        ),
        "why_synthetic": (
            "The repo ships 7 tickers x ~43 daily observations, far below the 252-day minimum "
            "training window the validator requires. Synthetic series let the harness actually run "
            "and expose the *relative* ranking of models. They are NOT a claim of real-market skill."
        ),
    }
    rng = np.random.default_rng(SEED)
    n = 1400

    # Series A: AR(1) with genuine autocorrelation (phi=0.35) -> structure IS learnable
    phi = 0.35
    a = np.zeros(n)
    eps = rng.normal(0, 0.01, n)
    for t in range(1, n):
        a[t] = phi * a[t - 1] + eps[t]
    series_ar1 = pd.Series(a)

    # Series B: pure Gaussian white-noise returns (efficient-market-like) -> nothing beats naive
    series_noise = pd.Series(rng.normal(0.0003, 0.011, n))

    out["series_A_ar1_phi0.35"] = _run_walkforward(series_ar1, "AR1")
    out["series_B_white_noise"] = _run_walkforward(series_noise, "NOISE")

    out["interpretation"] = (
        "On the AR(1) series (real structure) the learning models cut MSE vs the last-value naive "
        "baseline, confirming the pipeline extracts signal when signal exists. On white-noise returns "
        "(closer to real equity returns) NO model meaningfully beats the naive baselines - the honest, "
        "expected result and the reason the README must not claim a fixed '% MSE improvement over ARIMA' "
        "on real markets."
    )

    # Chart: MSE-vs-last-value uplift per model, both series
    def uplift(block):
        return {k: v.get("mse_vs_last_value_pct", 0.0)
                for k, v in block["models"].items() if isinstance(v, dict) and "mse" in v}
    ua, ub = uplift(out["series_A_ar1_phi0.35"]), uplift(out["series_B_white_noise"])
    names = [k for k in ua if k != "last_value"]
    x = np.arange(len(names)); w = 0.38
    fig, ax = plt.subplots(figsize=(11, 4.6))
    ax.bar(x - w / 2, [ua[k] for k in names], w, label="AR(1) — has signal", color=C1)
    ax.bar(x + w / 2, [ub[k] for k in names], w, label="white noise — no signal", color=C2)
    ax.axhline(0, color="grey", lw=1)
    ax.set_xticks(x); ax.set_xticklabels(names, rotation=25, ha="right", fontsize=8)
    _style(ax, "MSE reduction vs last-value naive baseline (walk-forward)", "", "% MSE reduction")
    ax.legend()
    fig.tight_layout()
    fig.savefig(os.path.join(CHARTS, "ml_walkforward.png"), dpi=130)
    plt.close(fig)
    return out


