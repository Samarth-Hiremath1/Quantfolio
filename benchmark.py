"""
QuantFolio Benchmark Harness
============================

Reproducible, self-contained benchmarks that measure ONLY what the codebase can
actually do. Every number written to ``benchmark_results.json`` is produced by
running the real modules in this repository (or clearly-labelled synthetic data
where real data is too small).

Design principles
-----------------
* No fabricated numbers. If something cannot be measured in this environment
  (e.g. Dockerised Postgres API latency), it is recorded as ``"status":
  "not_measured"`` with the reason, rather than invented.
* Deterministic. All RNGs are seeded so re-runs reproduce the same figures.
* Honest labelling. Synthetic series used for the ML walk-forward are flagged as
  synthetic; they demonstrate the *validation harness and relative model
  ranking*, not a claim about real-market alpha.

Run:  ``python benchmark.py``
Outputs: ``benchmark_results.json``, ``charts/*.png``
"""
